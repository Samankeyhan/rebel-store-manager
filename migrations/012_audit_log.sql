-- Audit log: an append-only record of every write to an accounting table.
--
-- audit_log          one row per INSERT / UPDATE / DELETE on an audited table. UPDATE rows hold
--                    only the changed columns (before_json / after_json); INSERT holds the whole
--                    new row (after_json), DELETE the whole old row (before_json). Money is
--                    integer Rial, exactly as in the table. ts is UTC, like every stored moment.
-- audit_context      one row while a labelled business operation runs (db/audit.py audit_operation):
--                    its name, a shared op_id and the optional actor. Empty = 'UNLABELLED'.
-- audit_control      allow_purge is 1 only inside db/audit.py reset_audit_log, the one deliberate
--                    way to clear the log (after writing an archive).
--
-- The triggers write in the SAME transaction as the change: a failed change leaves no row and a
-- failed log insert undoes the change. They are generated by db/audit.py audit_trigger_sql from
-- the schema as of migration 011; tests/test_audit.py fails when a table or column is not
-- covered, so a later migration that adds one must regenerate that table's trg_audit_* triggers
-- (and any column that should stay out of the log goes in db/audit.py UNAUDITED_COLUMNS).
-- Excluded: counters, schema_migrations and the audit tables, plus the updated_at column.
--
-- Nothing is backfilled and no updated_at is touched: existing rows are not logged.

CREATE TABLE audit_log (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    ts          TEXT NOT NULL DEFAULT (datetime('now')),
    entity_type TEXT NOT NULL,
    entity_id   TEXT NOT NULL,
    action      TEXT NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    operation   TEXT NOT NULL,
    before_json TEXT CHECK (before_json IS NULL OR json_valid(before_json)),
    after_json  TEXT CHECK (after_json IS NULL OR json_valid(after_json)),
    actor       TEXT,
    op_id       TEXT
);

CREATE INDEX idx_audit_log_entity ON audit_log(entity_type, entity_id, id);
CREATE INDEX idx_audit_log_ts     ON audit_log(ts);
CREATE INDEX idx_audit_log_op     ON audit_log(op_id);

CREATE TABLE audit_context (
    id        INTEGER PRIMARY KEY CHECK (id = 1),
    op_id     TEXT NOT NULL,
    operation TEXT NOT NULL,
    actor     TEXT
);

CREATE TABLE audit_control (
    id          INTEGER PRIMARY KEY CHECK (id = 1),
    allow_purge INTEGER NOT NULL DEFAULT 0 CHECK (allow_purge IN (0, 1))
);
INSERT INTO audit_control (id, allow_purge) VALUES (1, 0);

CREATE TRIGGER trg_audit_log_no_update BEFORE UPDATE ON audit_log
BEGIN
    SELECT RAISE(ABORT, 'audit_log is append-only');
END;

CREATE TRIGGER trg_audit_log_no_delete BEFORE DELETE ON audit_log
WHEN (SELECT allow_purge FROM audit_control WHERE id = 1) = 0
BEGIN
    SELECT RAISE(ABORT, 'audit_log is append-only');
END;

-- categories
CREATE TRIGGER trg_audit_categories_ins AFTER INSERT ON categories
BEGIN
    INSERT INTO audit_log (entity_type, entity_id, action, operation, after_json, actor, op_id)
    SELECT 'categories', CAST(NEW.id AS TEXT), 'INSERT', COALESCE(c.operation, 'UNLABELLED'),
           json_object('id', NEW.id, 'kind', NEW.kind, 'name', NEW.name, 'parent_id', NEW.parent_id, 'is_active', NEW.is_active, 'created_at', NEW.created_at), c.actor, c.op_id
    FROM (SELECT 1) AS one LEFT JOIN audit_context AS c ON c.id = 1;
END;

CREATE TRIGGER trg_audit_categories_upd AFTER UPDATE ON categories
BEGIN
    INSERT INTO audit_log (entity_type, entity_id, action, operation, before_json, after_json, actor, op_id)
    SELECT 'categories', CAST(NEW.id AS TEXT), 'UPDATE', COALESCE(c.operation, 'UNLABELLED'),
           json_group_object(d.k, d.o), json_group_object(d.k, d.n), c.actor, c.op_id
    FROM (
        SELECT 'id' AS k, OLD.id AS o, NEW.id AS n
        UNION ALL SELECT 'kind' AS k, OLD.kind AS o, NEW.kind AS n
        UNION ALL SELECT 'name' AS k, OLD.name AS o, NEW.name AS n
        UNION ALL SELECT 'parent_id' AS k, OLD.parent_id AS o, NEW.parent_id AS n
        UNION ALL SELECT 'is_active' AS k, OLD.is_active AS o, NEW.is_active AS n
        UNION ALL SELECT 'created_at' AS k, OLD.created_at AS o, NEW.created_at AS n
    ) AS d
    LEFT JOIN audit_context AS c ON c.id = 1
    WHERE d.o IS NOT d.n
    HAVING count(*) > 0;
END;

CREATE TRIGGER trg_audit_categories_del AFTER DELETE ON categories
