"""Append-only audit log of every write to an accounting table (docs/accounting-rules.md, "Audit log").
SQLite triggers (generated by `audit_trigger_sql`, written into the migrations) log each INSERT / UPDATE / DELETE on the audited tables in the SAME transaction as the change: a failed change leaves no row and a failed log insert undoes the change. UPDATE rows hold only the changed columns.
Money in the log is integer Rial, as in the tables."""

import sqlite3

# Tables that have no audit triggers: bookkeeping and the audit tables themselves.
# A new table is audited by default; add it here only with a reason.
UNAUDITED_TABLES = frozenset({
    "counters",            # invoice numbering; the number sits on the order / purchase row
    "schema_migrations",
    "audit_log",
    "audit_context",
    "audit_control",
})

# Columns left out of every UPDATE diff (they carry no accounting meaning). Extend this
# set (for example with "name_key") before adding such a column; the coverage test reads it.
UNAUDITED_COLUMNS = frozenset({"updated_at"})

_ACTIONS = ("INSERT", "UPDATE", "DELETE")

# ---------------------------------------------------------------- trigger SQL


def audited_table_columns(conn: sqlite3.Connection) -> dict[str, list[dict]]:
    """{table: PRAGMA table_info rows} for every table that must have audit triggers."""
    tables = [
        row[0]
        for row in conn.execute(
            "SELECT name FROM sqlite_master WHERE type = 'table' "
            "AND name NOT LIKE 'sqlite_%' ORDER BY name"
        )
    ]
    return {
        table: [dict(r) for r in conn.execute(f"PRAGMA table_info({table})")]
        for table in tables
        if table not in UNAUDITED_TABLES
    }


def _primary_key(table: str, columns: list[dict]) -> str:
    keys = [c["name"] for c in columns if c["pk"]]
    if len(keys) != 1:
        raise ValueError(f"audit triggers need a single-column primary key on {table}, got {keys}")
    return keys[0]


def audit_trigger_sql(table: str, columns: list[dict]) -> str:
    """The three audit triggers of one table, for a migration file.

    `columns` is PRAGMA table_info. Run it against a database at the schema the
    migration starts from, and paste the output into the new migration (drop the
    table's old trg_audit_* triggers first when columns changed)."""
    key = _primary_key(table, columns)
    tracked = [c["name"] for c in columns if c["name"] not in UNAUDITED_COLUMNS]
    context = (
        "FROM (SELECT 1) AS one LEFT JOIN audit_context AS c ON c.id = 1"
    )
    entity = f"'{table}', CAST({{row}}.{key} AS TEXT)"

    def row_json(row: str) -> str:
        return "json_object(" + ", ".join(f"'{n}', {row}.{n}" for n in tracked) + ")"

    diff = "\n        UNION ALL ".join(
        f"SELECT '{n}' AS k, OLD.{n} AS o, NEW.{n} AS n" for n in tracked
    )
    return f"""
CREATE TRIGGER trg_audit_{table}_ins AFTER INSERT ON {table}
BEGIN
    INSERT INTO audit_log (entity_type, entity_id, action, operation, after_json, actor, op_id)
    SELECT {entity.format(row="NEW")}, 'INSERT', COALESCE(c.operation, 'UNLABELLED'),
           {row_json("NEW")}, c.actor, c.op_id
    {context};
END;

CREATE TRIGGER trg_audit_{table}_upd AFTER UPDATE ON {table}
BEGIN
    INSERT INTO audit_log (entity_type, entity_id, action, operation, before_json, after_json, actor, op_id)
    SELECT {entity.format(row="NEW")}, 'UPDATE', COALESCE(c.operation, 'UNLABELLED'),
           json_group_object(d.k, d.o), json_group_object(d.k, d.n), c.actor, c.op_id
    FROM (
        {diff}
    ) AS d
    LEFT JOIN audit_context AS c ON c.id = 1
    WHERE d.o IS NOT d.n
    HAVING count(*) > 0;
END;

CREATE TRIGGER trg_audit_{table}_del AFTER DELETE ON {table}
BEGIN
    INSERT INTO audit_log (entity_type, entity_id, action, operation, before_json, actor, op_id)
    SELECT {entity.format(row="OLD")}, 'DELETE', COALESCE(c.operation, 'UNLABELLED'),
           {row_json("OLD")}, c.actor, c.op_id
    {context};
END;
"""
