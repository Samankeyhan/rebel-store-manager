"""Append-only audit log of every write to an accounting table (docs/accounting-rules.md, "Audit log").
SQLite triggers (generated by `audit_trigger_sql`, written into the migrations) log each INSERT / UPDATE / DELETE on the audited tables in the SAME transaction as the change: a failed change leaves no row and a failed log insert undoes the change. UPDATE rows hold only the changed columns.
`audited` / `audit_operation` label a business operation (name, `op_id` grouping its rows, optional actor); a write outside them is still logged as 'UNLABELLED'.
`list_audit_log` reads; `reset_audit_log` is the only way to clear the log (archive first). Money in the log is integer Rial, as in the tables."""

import contextlib
import contextvars
import functools
import hashlib
import json
import sqlite3
import uuid
from pathlib import Path

from db.connection import transaction
from db.errors import ValidationError
from db.timeutil import now_utc, to_utc_range

# Tables that have no audit triggers: bookkeeping and the audit tables themselves.
# A new table is audited by default; add it here only with a reason.
UNAUDITED_TABLES = frozenset({
    "counters",            # invoice numbering; the number sits on the order / purchase row
    "schema_migrations",
    "audit_log",
    "audit_context",
    "audit_control",
})

# set before adding a column that should stay out of the log; the coverage test reads it.
# set (for example with "name_key") before adding such a column; the coverage test reads it.
UNAUDITED_COLUMNS = frozenset({"updated_at", "name_key"})  # name_key: derived from name (db/names.py)

_ACTIONS = ("INSERT", "UPDATE", "DELETE")

# Who does the write. None until a multi-user layer sets it; no authentication here.
current_actor: contextvars.ContextVar[str | None] = contextvars.ContextVar(
    "audit_actor", default=None
)

MAX_PAGE_SIZE = 500
DEFAULT_PAGE_SIZE = 50


# ---------------------------------------------------------------- trigger SQL


def audited_table_columns(conn: sqlite3.Connection) -> dict[str, list[dict]]:
    """{table: PRAGMA table_info rows} for every table that must have audit triggers."""
    tables = [
        row[0]
        for row in conn.execute(
            "SELECT name FROM sqlite_master WHERE type = 'table' "
            "AND name NOT LIKE 'sqlite_%' ORDER BY name"
        )
    ]
    return {
        table: [dict(r) for r in conn.execute(f"PRAGMA table_info({table})")]
        for table in tables
        if table not in UNAUDITED_TABLES
    }


def _primary_key(table: str, columns: list[dict]) -> str:
    keys = [c["name"] for c in columns if c["pk"]]
    if len(keys) != 1:
        raise ValueError(f"audit triggers need a single-column primary key on {table}, got {keys}")
    return keys[0]


def audit_trigger_sql(table: str, columns: list[dict]) -> str:
    """The three audit triggers of one table, for a migration file.

    `columns` is PRAGMA table_info. Run it against a database at the schema the
    migration starts from, and paste the output into the new migration (drop the
    table's old trg_audit_* triggers first when columns changed)."""
    key = _primary_key(table, columns)
    tracked = [c["name"] for c in columns if c["name"] not in UNAUDITED_COLUMNS]
    context = (
        "FROM (SELECT 1) AS one LEFT JOIN audit_context AS c ON c.id = 1"
    )
    entity = f"'{table}', CAST({{row}}.{key} AS TEXT)"

    def row_json(row: str) -> str:
        return "json_object(" + ", ".join(f"'{n}', {row}.{n}" for n in tracked) + ")"

    diff = "\n        UNION ALL ".join(
        f"SELECT '{n}' AS k, OLD.{n} AS o, NEW.{n} AS n" for n in tracked
    )
    return f"""
CREATE TRIGGER trg_audit_{table}_ins AFTER INSERT ON {table}
BEGIN
    INSERT INTO audit_log (entity_type, entity_id, action, operation, after_json, actor, op_id)
    SELECT {entity.format(row="NEW")}, 'INSERT', COALESCE(c.operation, 'UNLABELLED'),
           {row_json("NEW")}, c.actor, c.op_id
    {context};
END;

CREATE TRIGGER trg_audit_{table}_upd AFTER UPDATE ON {table}
BEGIN
    INSERT INTO audit_log (entity_type, entity_id, action, operation, before_json, after_json, actor, op_id)
    SELECT {entity.format(row="NEW")}, 'UPDATE', COALESCE(c.operation, 'UNLABELLED'),
           json_group_object(d.k, d.o), json_group_object(d.k, d.n), c.actor, c.op_id
    FROM (
        {diff}
    ) AS d
    LEFT JOIN audit_context AS c ON c.id = 1
    WHERE d.o IS NOT d.n
    HAVING count(*) > 0;
END;

CREATE TRIGGER trg_audit_{table}_del AFTER DELETE ON {table}
BEGIN
    INSERT INTO audit_log (entity_type, entity_id, action, operation, before_json, actor, op_id)
    SELECT {entity.format(row="OLD")}, 'DELETE', COALESCE(c.operation, 'UNLABELLED'),
           {row_json("OLD")}, c.actor, c.op_id
    {context};
END;
"""


def stale_audit_tables(conn: sqlite3.Connection) -> list[str]:
    """Audited tables whose trg_audit_* triggers differ from what `audit_trigger_sql` generates
    for the table's current columns (a column added without regenerated triggers)."""

    def squash(sql: str) -> str:
        return " ".join(sql.split())

    def stored(name: str) -> str:
        row = conn.execute(
            "SELECT sql FROM sqlite_master WHERE type = 'trigger' AND name = ?", (name,)
        ).fetchone()
        return squash(row[0]) if row else "MISSING"

    stale = []
    for table, columns in audited_table_columns(conn).items():
        actual = " ".join(stored(f"trg_audit_{table}_{kind}") + ";" for kind in ("ins", "upd", "del"))
        if actual != squash(audit_trigger_sql(table, columns)):
            stale.append(table)
    return stale


# ----------------------------------------------------------------- operations


@contextlib.contextmanager
def audit_operation(conn: sqlite3.Connection, operation: str, actor: str | None = None):
    """One business operation: everything written inside shares an `op_id`, the
    `operation` label and the actor. Nested calls join the outermost one.
    Always a transaction (a savepoint inside an open one)."""
    with transaction(conn):
        if conn.execute("SELECT 1 FROM audit_context WHERE id = 1").fetchone() is not None:
            yield
            return
        conn.execute(
            "INSERT INTO audit_context (id, op_id, operation, actor) VALUES (1, ?, ?, ?)",
            (uuid.uuid4().hex, operation, actor if actor is not None else current_actor.get()),
        )
        yield
        conn.execute("DELETE FROM audit_context WHERE id = 1")


def audited(operation: str | None = None):
    """Decorator for a public write function whose first argument is the connection:
    runs it as one labelled audit operation (default label = the function name)."""

    def decorate(func):
        label = operation or func.__name__

        @functools.wraps(func)
        def wrapper(*args, **kwargs):
            conn = args[0] if args else kwargs["conn"]
            with audit_operation(conn, label):
                return func(*args, **kwargs)

        return wrapper

    return decorate


# --------------------------------------------------------------------- reading


def _entry(row: sqlite3.Row) -> dict:
    entry = dict(row)
    for source, target in (("before_json", "before"), ("after_json", "after")):
        raw = entry.pop(source)
        entry[target] = json.loads(raw) if raw is not None else None
    return entry


def list_audit_log(
    conn: sqlite3.Connection,
    entity_type: str | None = None,
    entity_id: str | int | None = None,
    op_id: str | None = None,
    operation: str | None = None,
    start_date: str | None = None,
    end_date: str | None = None,
    limit: int = DEFAULT_PAGE_SIZE,
    offset: int = 0,
) -> dict:
    """{"items": newest first, "total": rows matching the filters}. Dates are local
    calendar days ("YYYY-MM-DD"), inclusive."""
    if isinstance(limit, bool) or not isinstance(limit, int) or not 1 <= limit <= MAX_PAGE_SIZE:
        raise ValidationError(
            f"limit must be an integer from 1 to {MAX_PAGE_SIZE}, got {limit!r}", field="limit"
        )
    if isinstance(offset, bool) or not isinstance(offset, int) or offset < 0:
        raise ValidationError(f"offset must be an integer >= 0, got {offset!r}", field="offset")

    where = ["1 = 1"]
    params: list = []
    for column, value in (
        ("entity_type", entity_type),
        ("entity_id", None if entity_id is None else str(entity_id)),
        ("op_id", op_id),
        ("operation", operation),
    ):
        if value is not None:
            where.append(f"{column} = ?")
            params.append(value)
    start_utc, end_exclusive_utc = to_utc_range(start_date, end_date, conn)
    if start_utc is not None:
        where.append("ts >= ?")
        params.append(start_utc)
    if end_exclusive_utc is not None:
        where.append("ts < ?")
        params.append(end_exclusive_utc)
    clause = " AND ".join(where)

    total = conn.execute(f"SELECT COUNT(*) FROM audit_log WHERE {clause}", params).fetchone()[0]
    rows = conn.execute(
        f"SELECT * FROM audit_log WHERE {clause} ORDER BY id DESC LIMIT ? OFFSET ?",
        [*params, limit, offset],
    ).fetchall()
    return {"items": [_entry(row) for row in rows], "total": total}


# ----------------------------------------------------------------------- reset


def _default_archive_path(conn: sqlite3.Connection) -> Path:
    """<database folder>/backups/audit-archive-<stamp>.jsonl, next to the database
    backups (data/backups/ for the shop database, which is gitignored)."""
    file = next((row["file"] for row in conn.execute("PRAGMA database_list") if row["name"] == "main"), "")
    if not file:
        raise ValidationError(
            "An in-memory database has no backups folder: pass archive_path", field="archive_path"
        )
    stamp = now_utc().replace("-", "").replace(":", "").replace(" ", "-")
    folder = Path(file).parent / "backups"
    path = folder / f"audit-archive-{stamp}.jsonl"
    suffix = 1
    while path.exists():
        path = folder / f"audit-archive-{stamp}-{suffix}.jsonl"
        suffix += 1
    return path


def reset_audit_log(conn: sqlite3.Connection, archive_path: str | Path | None = None) -> dict:
    """Deliberately clear the log (the go-live reset). Every row is first written to a
    JSON-lines archive (default: <database folder>/backups/, never overwritten) and the
    archive is checked; then, in one transaction, the rows are deleted and a single
    'reset_audit_log' row records how many went where. Any failure leaves the log as it was."""
    path = Path(archive_path) if archive_path is not None else _default_archive_path(conn)
    if path.exists():
        raise ValidationError(f"Archive file already exists: {path}", field="archive_path")
    path.parent.mkdir(parents=True, exist_ok=True)

    with transaction(conn):
        rows = conn.execute("SELECT * FROM audit_log ORDER BY id").fetchall()
        digest = hashlib.sha256()
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            for row in rows:
                line = json.dumps(dict(row), ensure_ascii=False, sort_keys=True) + "\n"
                digest.update(line.encode("utf-8"))
                handle.write(line)
        written = path.read_bytes()
        if written.count(b"\n") != len(rows) or hashlib.sha256(written).hexdigest() != digest.hexdigest():
            path.unlink(missing_ok=True)
            raise RuntimeError(f"Audit archive {path} did not verify; the log was not cleared")

        conn.execute("UPDATE audit_control SET allow_purge = 1 WHERE id = 1")
        conn.execute("DELETE FROM audit_log")
        conn.execute("UPDATE audit_control SET allow_purge = 0 WHERE id = 1")
        summary = {"rows": len(rows), "archive": path.name, "sha256": digest.hexdigest()}
        conn.execute(
            "INSERT INTO audit_log (entity_type, entity_id, action, operation, before_json) "
            "VALUES ('audit_log', 'reset', 'DELETE', 'reset_audit_log', ?)",
            (json.dumps(summary, sort_keys=True),),
        )
    return {**summary, "path": str(path)}
